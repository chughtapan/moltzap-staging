/** @file Creates daemon configuration and ownership records before agent services start. */

import { Migrator, SqlClient } from "@effect/sql";
import { Effect } from "effect";

// safer-arch-ignore no-trivial-sink-file: Versioned schema definitions remain separate from their process initialization caller.

/** A reset format distinguishes incompatible layouts independently of additive migration numbers. */
export const daemonDatabaseFormat = 3;

const ownershipSchema = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  yield* sql`CREATE TABLE daemon_settings (
    singleton INTEGER PRIMARY KEY CHECK(singleton = 1), settings TEXT NOT NULL
  )`;
  yield* sql`CREATE TABLE owner_bindings (
    agent_key TEXT PRIMARY KEY,
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    UNIQUE(issuer, subject)
  )`;
  yield* sql`CREATE TABLE agent_profiles (
    agent_key TEXT PRIMARY KEY REFERENCES owner_bindings(agent_key),
    agent_name TEXT NOT NULL UNIQUE,
    principal_id TEXT NOT NULL,
    registration_operation_id TEXT NOT NULL,
    private_key TEXT NOT NULL
  )`;
  yield* sql.onDialectOrElse({
    pg: () =>
      Effect.gen(function* () {
        yield* sql`ALTER TABLE agent_profiles ENABLE ROW LEVEL SECURITY`;
        yield* sql`ALTER TABLE agent_profiles FORCE ROW LEVEL SECURITY`;
        yield* sql`CREATE POLICY agent_profile_owner ON agent_profiles
        USING (agent_key = current_setting('social_harness.agent_key', true))
        WITH CHECK (agent_key = current_setting('social_harness.agent_key', true))`;
      }),
    orElse: () => Effect.void,
  });
});

const agentStateSchema = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  const binary = sql.onDialectOrElse({
    pg: () => "BYTEA",
    orElse: () => "BLOB",
  });
  const sequence = sql.onDialectOrElse({
    pg: () => "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    orElse: () => "INTEGER PRIMARY KEY AUTOINCREMENT",
  });
  yield* sql.unsafe(`CREATE TABLE identity_binding (
    agent_key TEXT PRIMARY KEY,
    agent_id TEXT NOT NULL,
    canonical_agent_card ${binary} NOT NULL
  )`);
  yield* sql.unsafe(`CREATE TABLE harness_items (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    identity TEXT NOT NULL,
    token TEXT NOT NULL,
    address TEXT NOT NULL,
    kind TEXT NOT NULL,
    author TEXT,
    message_id TEXT,
    operation_id TEXT,
    incoming ${binary},
    view ${binary},
    status TEXT NOT NULL CHECK(status IN ('checking','withheld','pending','acknowledged')),
    UNIQUE(agent_key, identity),
    UNIQUE(agent_key, token)
  )`);
  yield* sql`CREATE INDEX harness_pending ON harness_items(agent_key,status,sequence)`;
  yield* sql`CREATE INDEX harness_conversation ON harness_items(agent_key,address,sequence)`;
  yield* sql`CREATE INDEX harness_message ON harness_items(agent_key,author,message_id)`;
  yield* sql`CREATE INDEX harness_request ON harness_items(agent_key,operation_id)`;
  yield* sql`CREATE TABLE harness_visibility (
    agent_key TEXT NOT NULL, author TEXT NOT NULL, message_id TEXT NOT NULL,
    visible INTEGER NOT NULL, PRIMARY KEY(agent_key, author, message_id)
  )`;
  yield* sql`CREATE TABLE mcp_webhook_state (agent_key TEXT PRIMARY KEY, state TEXT NOT NULL)`;
  yield* sql.onDialectOrElse({
    pg: () =>
      Effect.forEach(
        [
          "identity_binding",
          "harness_items",
          "harness_visibility",
          "mcp_webhook_state",
        ],
        (table) =>
          Effect.gen(function* () {
            yield* sql`ALTER TABLE ${sql(table)} ENABLE ROW LEVEL SECURITY`;
            yield* sql`ALTER TABLE ${sql(table)} FORCE ROW LEVEL SECURITY`;
            yield* sql`CREATE POLICY agent_owner ON ${sql(table)}
        USING (agent_key = current_setting('social_harness.agent_key', true))
        WITH CHECK (agent_key = current_setting('social_harness.agent_key', true))`;
          }),
        { concurrency: 1 },
      ),
    orElse: () => Effect.void,
  });
  yield* sql.onDialectOrElse({
    sqlite: () => sql.unsafe(`PRAGMA user_version = ${daemonDatabaseFormat}`),
    orElse: () => Effect.void,
  });
});

const firewallSchema = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  const binary = sql.onDialectOrElse({
    pg: () => "BYTEA",
    orElse: () => "BLOB",
  });
  const sequence = sql.onDialectOrElse({
    pg: () => "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    orElse: () => "INTEGER PRIMARY KEY AUTOINCREMENT",
  });
  yield* sql.unsafe(`CREATE TABLE firewall_checks (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    check_id TEXT NOT NULL,
    direction TEXT NOT NULL CHECK(direction IN ('incoming','outgoing')),
    canonical_candidate ${binary} NOT NULL,
    canonical_input ${binary} NOT NULL,
    canonical_result ${binary} NOT NULL,
    decided_at BIGINT NOT NULL,
    disposition TEXT NOT NULL CHECK(disposition IN ('admitted','withheld')),
    UNIQUE(agent_key, check_id)
  )`);
  yield* sql.unsafe(`CREATE TABLE firewall_policy (
    agent_key TEXT PRIMARY KEY,
    canonical_rules ${binary} NOT NULL
  )`);
  yield* sql.unsafe(`CREATE TABLE firewall_activations (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    activated_at BIGINT NOT NULL,
    active_revision TEXT NOT NULL,
    added_rule_ids TEXT NOT NULL,
    removed_rule_ids TEXT NOT NULL
  )`);
  yield* sql`CREATE INDEX firewall_activations_time ON firewall_activations(agent_key,activated_at,sequence)`;
  yield* sql`CREATE INDEX firewall_decisions_time ON firewall_checks(agent_key,decided_at,sequence)`;
  yield* sql.onDialectOrElse({
    pg: () =>
      Effect.forEach(
        ["firewall_checks", "firewall_policy", "firewall_activations"],
        (table) =>
          Effect.gen(function* () {
            yield* sql`ALTER TABLE ${sql(table)} ENABLE ROW LEVEL SECURITY`;
            yield* sql`ALTER TABLE ${sql(table)} FORCE ROW LEVEL SECURITY`;
            yield* sql`CREATE POLICY agent_owner ON ${sql(table)}
          USING (agent_key = current_setting('social_harness.agent_key', true))
          WITH CHECK (agent_key = current_setting('social_harness.agent_key', true))`;
          }),
        { concurrency: 1 },
      ),
    orElse: () => Effect.void,
  });
});

const columnTypes = Effect.map(SqlClient.SqlClient, (sql) => ({
  binary: sql.onDialectOrElse({ pg: () => "BYTEA", orElse: () => "BLOB" }),
  sequence: sql.onDialectOrElse({
    pg: () => "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    orElse: () => "INTEGER PRIMARY KEY AUTOINCREMENT",
  }),
}));

const conversationTables = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  const { binary, sequence } = yield* columnTypes;
  yield* sql`CREATE TABLE communication_metadata (
    agent_key TEXT PRIMARY KEY, agent_id TEXT NOT NULL
  )`;
  yield* sql.unsafe(`CREATE TABLE memberships (
    agent_key TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    membership_hash TEXT NOT NULL,
    canonical_membership ${binary} NOT NULL,
    sort_key TEXT NOT NULL,
    PRIMARY KEY (agent_key, conversation_id),
    UNIQUE(agent_key,sort_key),
    UNIQUE(agent_key,conversation_id, membership_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE anchors (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    conversation_id TEXT NOT NULL,
    anchor_hash TEXT NOT NULL,
    previous_anchor_hash TEXT,
    selected_record_hash TEXT,
    canonical_anchor ${binary} NOT NULL,
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    UNIQUE (agent_key, conversation_id, anchor_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE conversation_state (
    agent_key TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    membership_hash TEXT NOT NULL,
    current_anchor_hash TEXT NOT NULL,
    head_record_hash TEXT,
    head_ordinal INTEGER NOT NULL CHECK (head_ordinal >= -1),
    PRIMARY KEY (agent_key, conversation_id),
    FOREIGN KEY (agent_key, conversation_id) REFERENCES memberships(agent_key,conversation_id),
    FOREIGN KEY (agent_key,conversation_id, current_anchor_hash)
      REFERENCES anchors(agent_key,conversation_id, anchor_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE proposal_locks (
    agent_key TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    predecessor_key TEXT NOT NULL,
    previous_record_hash TEXT,
    action_hash TEXT NOT NULL,
    canonical_action_core ${binary} NOT NULL,
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    PRIMARY KEY (agent_key, conversation_id, predecessor_key),
    CHECK (
      (previous_record_hash IS NULL AND predecessor_key = '') OR
      (previous_record_hash IS NOT NULL AND predecessor_key = previous_record_hash)
    )
  )`);
});

const recordTables = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  const { binary, sequence } = yield* columnTypes;
  yield* sql.unsafe(`CREATE TABLE staged_records (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    conversation_id TEXT NOT NULL,
    record_hash TEXT NOT NULL,
    previous_record_hash TEXT,
    membership_hash TEXT NOT NULL,
    anchor_hash TEXT NOT NULL,
    action_hash TEXT NOT NULL,
    author_agent_id TEXT NOT NULL,
    msg_id TEXT NOT NULL,
    canonical_record_core ${binary} NOT NULL,
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    UNIQUE (agent_key, conversation_id, record_hash),
    FOREIGN KEY (agent_key,conversation_id, anchor_hash)
      REFERENCES anchors(agent_key,conversation_id, anchor_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE protocol_evidence (
    agent_key TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    evidence_kind TEXT NOT NULL CHECK (
      evidence_kind IN ('action', 'durability', 'catch-up', 'reanchor')
    ),
    subject_id TEXT NOT NULL,
    evidence_key TEXT NOT NULL,
    canonical_evidence ${binary} NOT NULL,
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    PRIMARY KEY (agent_key, conversation_id, evidence_kind, subject_id, evidence_key)
  )`);
  yield* sql.unsafe(`CREATE TABLE certified_records (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    conversation_id TEXT NOT NULL,
    record_hash TEXT NOT NULL,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    consumed INTEGER NOT NULL DEFAULT 0 CHECK (consumed IN (0,1)),
    UNIQUE (agent_key, conversation_id, record_hash),
    UNIQUE(agent_key,conversation_id, ordinal),
    FOREIGN KEY (agent_key,conversation_id, record_hash)
      REFERENCES staged_records(agent_key,conversation_id, record_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE reanchors (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    conversation_id TEXT NOT NULL,
    anchor_hash TEXT NOT NULL,
    previous_anchor_hash TEXT NOT NULL,
    router_instance_id TEXT NOT NULL,
    selected_record_hash TEXT NOT NULL,
    canonical_body ${binary} NOT NULL,
    canonical_completed_reanchor ${binary},
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    UNIQUE (agent_key, conversation_id, anchor_hash),
    UNIQUE(agent_key,conversation_id, previous_anchor_hash, router_instance_id),
    FOREIGN KEY (agent_key,conversation_id, previous_anchor_hash)
      REFERENCES anchors(agent_key,conversation_id, anchor_hash),
    FOREIGN KEY (agent_key,conversation_id, selected_record_hash)
      REFERENCES certified_records(agent_key,conversation_id, record_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE outbound_messages (
    agent_key TEXT NOT NULL,
    outbound_sequence ${sequence},
    conversation_id TEXT NOT NULL,
    envelope_id TEXT NOT NULL,
    record_hash TEXT,
    canonical_signed_message ${binary} NOT NULL,
    wire_version TEXT NOT NULL,
    attempted INTEGER NOT NULL CHECK (attempted IN (0, 1)),
    disposition TEXT NOT NULL CHECK (
      disposition IN ('pending', 'accepted', 'discarded')
    ),
    FOREIGN KEY (agent_key,conversation_id) REFERENCES memberships(agent_key,conversation_id),
    UNIQUE(agent_key,envelope_id),
    FOREIGN KEY (agent_key,conversation_id, record_hash) REFERENCES staged_records(agent_key,conversation_id, record_hash)
  )`);
  yield* sql.unsafe(`CREATE TABLE message_intents (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    author_agent_id TEXT NOT NULL,
    msg_id TEXT NOT NULL,
    conversation_id TEXT NOT NULL,
    membership_hash TEXT,
    canonical_message ${binary} NOT NULL,
    canonical_intent ${binary},
    completed_record_hash TEXT,
    failure_reason TEXT,
    UNIQUE (agent_key, author_agent_id, msg_id),
    FOREIGN KEY (agent_key,conversation_id, membership_hash)
      REFERENCES memberships(agent_key,conversation_id, membership_hash)
  )`);
});

const requestTables = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  const { binary, sequence } = yield* columnTypes;
  yield* sql.unsafe(`CREATE TABLE collective_operations (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    operation_id TEXT NOT NULL,
    creator_agent_id TEXT NOT NULL,
    origin TEXT NOT NULL CHECK(origin IN ('local','remote')),
    canonical_request ${binary} NOT NULL,
    deadline_at BIGINT NOT NULL,
    phase TEXT NOT NULL DEFAULT 'collecting' CHECK(phase IN ('collecting','finalizing','completed')),
    canonical_close ${binary},
    canonical_result ${binary},
    canonical_answer_refs ${binary},
    delivered INTEGER NOT NULL DEFAULT 0 CHECK(delivered IN (0,1)),
    UNIQUE (agent_key, operation_id)
  )`);
  yield* sql.unsafe(`CREATE TABLE collective_messages (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    operation_id TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('request','response','close')),
    destination TEXT NOT NULL,
    author_agent_id TEXT NOT NULL,
    msg_id TEXT NOT NULL,
    FOREIGN KEY (agent_key,operation_id) REFERENCES collective_operations(agent_key,operation_id),
    UNIQUE (agent_key, operation_id,role,destination),
    UNIQUE(agent_key,author_agent_id,msg_id)
  )`);
  yield* sql.unsafe(`CREATE TABLE collective_answers (
    agent_key TEXT NOT NULL,
    sequence ${sequence},
    operation_id TEXT NOT NULL,
    member TEXT NOT NULL,
    canonical_message ${binary} NOT NULL,
    FOREIGN KEY (agent_key,operation_id) REFERENCES collective_operations(agent_key,operation_id),
    UNIQUE (agent_key, operation_id,member)
  )`);
});

const communicationSchema = Effect.gen(function* () {
  const sql = yield* SqlClient.SqlClient;
  yield* conversationTables;
  yield* recordTables;
  yield* requestTables;
  yield* sql`CREATE INDEX message_intents_unresolved ON message_intents(agent_key,conversation_id)
    WHERE completed_record_hash IS NULL`;
  yield* sql`CREATE INDEX certified_records_by_hash ON certified_records(agent_key,record_hash)`;
  yield* sql`CREATE UNIQUE INDEX outbound_current_record ON outbound_messages(agent_key,conversation_id,record_hash)
    WHERE record_hash IS NOT NULL AND disposition<>'discarded'`;
  yield* sql`CREATE UNIQUE INDEX collective_one_response ON collective_messages(agent_key,operation_id) WHERE role='response'`;
  yield* sql`CREATE UNIQUE INDEX collective_one_close ON collective_messages(agent_key,operation_id) WHERE role='close'`;
  yield* sql`CREATE INDEX collective_pending_results ON collective_operations(agent_key,delivered) WHERE phase='completed' AND delivered=0`;
  yield* sql.onDialectOrElse({
    pg: () =>
      Effect.forEach(
        [
          "communication_metadata",
          "memberships",
          "anchors",
          "conversation_state",
          "proposal_locks",
          "staged_records",
          "protocol_evidence",
          "certified_records",
          "reanchors",
          "outbound_messages",
          "message_intents",
          "collective_operations",
          "collective_messages",
          "collective_answers",
        ],
        (table) =>
          Effect.gen(function* () {
            yield* sql`ALTER TABLE ${sql(table)} ENABLE ROW LEVEL SECURITY`;
            yield* sql`ALTER TABLE ${sql(table)} FORCE ROW LEVEL SECURITY`;
            yield* sql`CREATE POLICY agent_owner ON ${sql(table)}
          USING (agent_key = current_setting('social_harness.agent_key', true))
          WITH CHECK (agent_key = current_setting('social_harness.agent_key', true))`;
          }),
        { concurrency: 1 },
      ),
    orElse: () => Effect.void,
  });
});

/** Effect's migration ledger commits each schema change with its recorded version. */
export const migrateDaemon = Migrator.make({})({
  loader: Migrator.fromRecord({
    "0001_ownership": ownershipSchema,
    "0002_agent_state": agentStateSchema,
    "0003_firewall": firewallSchema,
    "0004_communication": communicationSchema,
  }),
});
